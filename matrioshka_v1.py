def analyze_simulation(log, nodes):
    total_jobs = len(log)
    assigned_jobs = sum(1 for entry in log if entry[1] is not None)
    rejected_jobs = total_jobs - assigned_jobs

    # Average score for assigned jobs only
    numeric_scores = [entry[2] for entry in log if isinstance(entry[2], float)]
    avg_score = round(sum(numeric_scores) / len(numeric_scores), 3)

    # Power usage and temperature
    total_power = sum(n.current_power for n in nodes)
    avg_temp = round(sum(n.temp for n in nodes) / len(nodes), 2)

    return {
        "Total Jobs": total_jobs,
        "Assigned Jobs": assigned_jobs,
        "Rejected Jobs": rejected_jobs,
        "Scheduling Success (%)": round((assigned_jobs / total_jobs) * 100, 2),
        "Average Efficiency Score": avg_score,
        "Final Total Power Consumption": total_power,
        "Average Temperature": avg_temp,
    }

